// Embeds the Selective Capital approval designs (src/lib/approvals/stock/*.html) as strings in
// src/lib/approvals/stock/generated.ts, so the production build carries them without reading the disk.
//   node scripts/generate-stock-designs.mjs           write the module
//   node scripts/generate-stock-designs.mjs --check   exit 1 when the module is not what the .html files give
// The .html files are the owner's designs and are copied byte for byte: never reformat them.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "approvals", "stock");

/** Slot order: the approval email, then the three follow-ups. */
export const FILES = {
  initial: "initial.html",
  followUp1: "follow-up-1.html",
  followUp2: "follow-up-2.html",
  followUp3: "follow-up-3.html",
};

/** The module's text for the current .html files. */
export function render() {
  const body = Object.entries(FILES)
    .map(([key, file]) => `  ${key}: ${JSON.stringify(readFileSync(join(dir, file), "utf8"))},`)
    .join("\n");
  return `// GENERATED by scripts/generate-stock-designs.mjs from the .html files in this folder. Do not edit by hand.
// A test (tests/stock-templates-source.test.ts) fails when this file and the .html files drift apart.
export const STOCK_HTML = {
${body}
} as const;
`;
}

const target = join(dir, "generated.ts");
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== render()) {
      console.error(
        "stock/generated.ts is out of date: run node scripts/generate-stock-designs.mjs",
      );
      process.exit(1);
    }
    console.log("stock/generated.ts matches the .html files");
  } else {
    writeFileSync(target, render());
    console.log("wrote src/lib/approvals/stock/generated.ts");
  }
}
